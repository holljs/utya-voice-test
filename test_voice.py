import os
import soundfile as sf
from supertonic import TTS

print("Инициализация Supertonic 3 TTS для сказки «Утя-Колобок»...")

tts = TTS(auto_download=True)
style = tts.get_voice_style(voice_name="F4")

kolobok_phrases = {
    # 1. Начало
    "kb_step1_q.wav": "Уутя сиде́л до́ма и о́чень скуучал. Реши́л он убежа́ть в лес. Что вы́берет Уутя?",

    # 2. Встреча с Зайкой
    "kb_step2_q.wav": "А навстре́чу За́йка-попрыга́йка. Стой, Уутя, я тебя́ пойма́ю! Ой, что же предложи́ть За́йке?",

    # 3. Встреча с Волком
    "kb_step3_q.wav": "Уутя побежа́л да́льше! А навстре́чу Се́рый Волк. Стой, Уутя, сейча́с я тебя́ пойма́ю! Что же подари́ть Во́лку?",

    # 4. Встреча с Медведем
    "kb_step4_q.wav": "А Уутя побежа́л да́льше, а навстре́чу Медве́дь. Кто туут шуми́т? Сейча́с пойма́ю! Что же предложи́ть Ми́шке?",

    # 5. Встреча с Лисичкой
    "kb_step5_q.wav": "Уутя побежа́л да́льше. Вдрууг из кусто́в выхо́дит хи́трая Лиси́чка. Ой, како́й Уутя хоро́шенький, иди́ ко мне́, я тебя́ пойма́ю! Что же придуумать?",

    # 6. Возвращение домой
    "kb_step6_q.wav": "Уутя вернуулся домо́й к ба́бушке и де́душке! Они́ так обра́довались! И что же они́ придуумали?",

    # 7. Финал
    "kb_step7_final.wav": "Вот и ска́зочке коне́ц, а кто игра́л и слуушал — тот су́пер-молоде́ц!",
}

print(f"Запуск синтеза {len(kolobok_phrases)} файлов для сказки «Утя-Колобок»...")

for filename, text in kolobok_phrases.items():
    print(f"Генерация: {filename}")
    try:
        wav, duration = tts.synthesize(
            text=text,
            lang="ru",
            voice_style=style,
            total_steps=10,
            speed=0.78
        )
        sf.write(filename, wav.squeeze(), 54000)
    except Exception as e:
        print(f"❌ Ошибка в {filename}: {e}")

print("✅ Все аудиофайлы для сказки «Утя-Колобок» полностью готовы!")
