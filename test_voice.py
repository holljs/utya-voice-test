# Ударения расставлены: ´ после гласной. Ударная "У" удвоена без знака ударения.
quiz_phrases = {
    
    # --- Лайфхаки: Магия на 9 (Пальчики) ---
    "magic9_1.wav": "Де́вять умно́жить на оди́н. Слеева ноль деся́тков, спра́ва де́вять едини́ц. Бу́дет де́вять!",
    "magic9_2.wav": "Де́вять умно́жить на два. Слеева оди́н деся́ток, спра́ва во́семь едини́ц. Бу́дет васемна́дцать!",
    "magic9_3.wav": "Де́вять умно́жить на три. Слеева два деся́тка, спра́ва семь едини́ц. Бу́дет два́дцать семь!",
    "magic9_4.wav": "Де́вять умно́жить на четы́ре. Слеева три деся́тка, спра́ва шесть едини́ц. Бу́дет три́дцать шесть!",
    "magic9_5.wav": "Де́вять умно́жить на пять. Слеева четы́ре деся́тка, спра́ва пять едини́ц. Бу́дет со́рок пять!",
    "magic9_6.wav": "Де́вять умно́жить на шесть. Слеева пять деся́тков, спра́ва четы́ре едини́цы. Бу́дет пятдеся́т четы́ре!",
    "magic9_7.wav": "Де́вять умно́жить на семь. Слеева шесть деся́тков, спра́ва три едини́цы. Бу́дет шестдеся́т три!",
    "magic9_8.wav": "Де́вять умно́жить на во́семь. Слеева семь деся́тков, спра́ва две едини́цы. Бу́дет се́мдесят два!",
    "magic9_9.wav": "Де́вять умно́жить на де́вять. Слеева во́семь деся́тков, спра́ва одна́ едини́ца. Бу́дет во́семдесят оди́н!",
    "magic9_10.wav": "Де́вять умно́жить на де́сять. Слеева де́вять деся́тков, спра́ва ноль едини́ц. Бу́дет девяно́сто!"
}

print(f"Запуск озвучки {len(quiz_phrases)} фраз...")

for filename, text in quiz_phrases.items():
    print(f"Синтез: {text} -> {filename}")
    try:
        wav, duration = tts.synthesize(
            text=text,
            lang="ru",
            voice_style=style,
            total_steps=10,
            speed=0.7 
        )
        sf.write(filename, wav.squeeze(), 54000)
    except Exception as e:
        print(f"❌ Ошибка при генерации {filename}: {e}")

print("✅ Успех! Все файлы для 'Нейро-Гения' готовы к скачиванию!")
