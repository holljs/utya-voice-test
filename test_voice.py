import soundfile as sf
from supertonic import TTS

print("Инициализация Supertonic 3 TTS...")
tts = TTS(auto_download=True)
style = tts.get_voice_style(voice_name="F4")

# Словарь: имя файла -> текст с ударениями и удвоенными 'у'
phrases = {
    # ------------------- Стихи Агнии Барто -------------------
    "myachik.wav": (
        "На́ша Та́ня грóмко пла́чет:\n"
        "Уурони́ла в ре́чку мя́чик.\n"
        "Ти́ше, Та́нечка, не пла́чь:\n"
        "Не уто́нет в ре́чке мя́ч."
    ),
    "mishka.wav": (
        "Уурони́ли ми́шку на́ по́л,\n"
        "Оторва́ли ми́шке ла́пу.\n"
        "Всё равно́ его́ не бро́шу —\n"
        "Потому́у что о́н хоро́ший."
    ),
    "zayka.wav": (
        "За́йку бро́сила хозя́йка —\n"
        "По́д дожде́м оста́лся за́йка.\n"
        "Со скаме́йки сле́зть не мо́г,\n"
        "Ве́сь до ни́точки промо́г."
    ),
    "bychok.wav": (
        "Идёт бычо́к, кача́ется,\n"
        "Вздыха́ет на ходу́у:\n"
        "— Ох, доска́ конча́ется,\n"
        "Сейча́с я упаду́у!"
    ),
    "gruzovik.wav": (
        "Не́т, напра́сно мы реши́ли\n"
        "Прокати́ть кота́ в маши́не:\n"
        "Ко́т ката́ться не привы́к —\n"
        "Опроки́нул грузови́к."
    ),

    # ------------------- Дополнительные фразы -------------------
    "oh_kakoe_zamechatelnoe.wav": (
        "Ой, како́е замеча́тельное стихотворе́ние!"
    ),
    "kak_krasivo.wav": (
        "Ка́к краси́во прочита́л!"
    ),
    "esche_stih.wav": (
        "Дава́й послу́шаем ещё оди́н стишо́к!"
    ),
    "ty_molodets.wav": (
        "Ты молоде́ц! Отли́чно получи́лось!"
    ),
}

print(f"Запуск озвучки {len(phrases)} фраз...")

for filename, text in phrases.items():
    print(f"Синтез: {text.splitlines()[0]}... -> {filename}")
    wav, duration = tts.synthesize(
        text=text,
        lang="ru",
        voice_style=style,
        total_steps=10,
        speed=0.7
    )
    sf.write(filename, wav.squeeze(), 54000)

print("✅ Готово! Все звуковые файлы успешно сгенерированы.")
