import os
import soundfile as sf
from supertonic import TTS

print("Инициализация Supertonic 3 TTS...")
tts = TTS(auto_download=True)
style = tts.get_voice_style(voice_name="F4")

# ---------- ВСЕ ФРАЗЫ ДЛЯ СОРОБАНА ----------
# Ударения расставлены: ´ после гласной. Ударная "У" удвоена без знака ударения.
quiz_phrases = {
    # --- Обучение: Простое сложение ---
    "learn_add_1.wav": "На спи́це уже́ есть два малыша́. Приба́вь к ним ещо́ двуух. Ста́ло четы́ре!",
    "learn_add_2.wav": "На спи́це три малыша́. Приба́вь к ним Короле́ву Пять, опусти́ ейо́ вниз. Полуучится во́семь.",
    "learn_add_3.wav": "На си́ней спи́це оди́н учени́к. Приба́вь к немуу ещо́ две сииних буусинки. Ста́ло три́дцать.",
    "learn_add_4.wav": "Попро́буем сра́зу две спи́цы! У нас число́ двена́дцать. Приба́вь Короле́ву Пять. Ста́ло семна́дцать.",
    "learn_add_5.wav": "А тепе́рь со́тни! Сэнсэ́й Пятьсо́т уже́ здесь. Приба́вь к немуу четыыре буусинки сниизу. Полуучится девятьсо́т!",

    # --- Обучение: Простое вычитание ---
    "learn_sub_1.wav": "На спи́це четы́ре малыша́. опусти́ двух вниз. Оста́нется два.",
    "learn_sub_2.wav": "На спи́це число́ во́семь. Короле́ва Пять ухо́дит наве́рх. Оста́нется три.",
    "learn_sub_3.wav": "У нас со́рок. Опусти́ вниз три сииних буусинки. Оста́нется де́сять.",
    "learn_sub_4.wav": "Число́ два́дцать семь. Короле́ва Пять ухо́дит наве́рх. Оста́нется два́дцать два.",
    "learn_sub_5.wav": "Бы́ло девятьсо́т, опусти́ четыыре буусины вниз, и оста́нется то́лько Сэнсэ́й Пятьсо́т."
}

print(f"Запуск озвучки {len(quiz_phrases)} фраз...")

for filename, text in quiz_phrases.items():
    print(f"Синтез: {text} -> {filename}")
    try:
        wav, duration = tts.synthesize(
            text=text,
            lang="ru",
            voice_style=style,
            total_steps=10,
            speed=0.7 
        )
        sf.write(filename, wav.squeeze(), 54000)
    except Exception as e:
        print(f"❌ Ошибка при генерации {filename}: {e}")

print("✅ Успех! Все файлы для 'Нейро-Гения' готовы к скачиванию!")
